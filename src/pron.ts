/** ཅ ཆ ཇ 右上角加一个小钩就是 ཙ ཚ ཛ */
export const HOOK_PAIRS: [string, string][] = [['ཅ', 'ཙ'], ['ཆ', 'ཚ'], ['ཇ', 'ཛ']]

const link = (pairs: [string, string][]) => {
  const m = new Map<string, Set<string>>()
  for (const [a, b] of pairs) {
    if (!m.has(a)) m.set(a, new Set())
    if (!m.has(b)) m.set(b, new Set())
    m.get(a)!.add(b)
    m.get(b)!.add(a)
  }
  return m
}
/** 字形相近的字 */
export const shapeMates = link([...SHAPE_PAIRS, ...HOOK_PAIRS])
/** 书上成对比较发音的字 */
export const soundMates = link(SOUND_PAIRS)
/** 字母或组合的注音 */
export const pronOf = (s: string) => (s.length === 1 ? PRON[s]?.[0] : CV_PRON[s]?.[0]) ?? ''
